-- Parceiros (no lugar de Instituições, pedido do dono em 16/11/2026): bancos, cooperativas, fintechs e fundos
-- com quem a Elev Muniz trabalha, com o contato de cada um. Os indicadores saem das propostas.
create table parceiros (
  id bigint generated by default as identity primary key,
  nome text not null,
  tipo text not null default 'Banco',
  documento text not null default '',
  contato_nome text not null default '',
  contato_cargo text not null default '',
  telefone text not null default '',
  email text not null default '',
  comissao_padrao numeric(6,2) not null default 0,
  prazo_resposta_dias integer not null default 0,
  observacao text not null default '',
  ativo integer not null default 1,
  exemplo integer not null default 0,
  criado_por text not null default '',
  criado_em text not null,
  atualizado_em text not null
);
create unique index parceiros_nome on parceiros (lower(nome));
alter table public.parceiros enable row level security;
