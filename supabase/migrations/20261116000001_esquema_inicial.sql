-- Hub Elev Muniz: o mesmo esquema do SQLite (migrações 1 a 3 de server/banco.js), em Postgres.
-- Datas continuam em texto ISO e os sim/não em 0/1 para o servidor funcionar igual ao de hoje.
-- Só a função do servidor (com a chave de serviço) acessa as tabelas: RLS ligado e sem políticas.

create table perfis_acesso (
  id bigint generated by default as identity primary key,
  nome text not null,
  descricao text not null default '',
  permissoes text not null default '{}',
  ativo integer not null default 1,
  criado_em text not null,
  atualizado_em text not null
);

create table usuarios (
  id bigint generated by default as identity primary key,
  nome text not null,
  email text not null,
  senha_hash text not null,
  admin integer not null default 0,
  perfil_acesso_id bigint references perfis_acesso(id) on delete set null,
  ativo integer not null default 1,
  trocar_senha integer not null default 0,
  ultimo_acesso_em text,
  criado_em text not null,
  atualizado_em text not null,
  exemplo integer not null default 0
);
create unique index usuarios_email on usuarios (lower(email));

create table configuracoes (
  chave text primary key,
  valor text not null
);

create table clientes (
  id bigint generated by default as identity primary key,
  nome text not null,
  pasta text not null,
  razao_social text not null default '',
  documento text not null default '',
  contato text not null default '',
  email text not null default '',
  telefone text not null default '',
  observacao text not null default '',
  ativo integer not null default 1,
  criado_por text not null default '',
  criado_em text not null,
  atualizado_em text not null,
  exemplo integer not null default 0,
  criado_por_id bigint
);
create unique index clientes_pasta on clientes (lower(pasta));

create table tipos_documento (
  id bigint generated by default as identity primary key,
  nome text not null,
  grupo text not null default 'Outros',
  descricao text not null default '',
  frente_verso integer not null default 0,
  exige_validade integer not null default 0,
  ordem integer not null default 0,
  removido_em text,
  criado_em text not null,
  atualizado_em text not null,
  exemplo integer not null default 0
);
create unique index tipos_documento_nome on tipos_documento (lower(nome)) where removido_em is null;

create table perfis_documento (
  id bigint generated by default as identity primary key,
  nome text not null,
  descricao text not null default '',
  ativo integer not null default 1,
  criado_em text not null,
  atualizado_em text not null,
  exemplo integer not null default 0
);

create table perfis_documento_itens (
  id bigint generated by default as identity primary key,
  perfil_id bigint not null references perfis_documento(id) on delete cascade,
  tipo_id bigint not null references tipos_documento(id) on delete cascade,
  obrigatorio integer not null default 1,
  ordem integer not null default 0
);
create unique index perfis_documento_itens_unico on perfis_documento_itens (perfil_id, tipo_id);

create table operacoes (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references clientes(id) on delete cascade,
  nome text not null,
  pasta text not null,
  descricao text not null default '',
  perfil_documento_id bigint references perfis_documento(id) on delete set null,
  perfil_documento_nome text not null default '',
  situacao text not null default 'ativa' check (situacao in ('ativa', 'encerrada')),
  criado_por text not null default '',
  criado_em text not null,
  atualizado_em text not null,
  consultor_id bigint references usuarios(id) on delete set null,
  etapa_id bigint,
  concluida_em text
);
create unique index operacoes_pasta on operacoes (cliente_id, lower(pasta));

create table operacao_itens (
  id bigint generated by default as identity primary key,
  operacao_id bigint not null references operacoes(id) on delete cascade,
  tipo_id bigint references tipos_documento(id) on delete set null,
  nome text not null,
  grupo text not null default 'Outros',
  descricao text not null default '',
  obrigatorio integer not null default 1,
  frente_verso integer not null default 0,
  exige_validade integer not null default 0,
  ordem integer not null default 0,
  removido_em text,
  criado_em text not null
);
create index operacao_itens_operacao on operacao_itens (operacao_id) where removido_em is null;

create table solicitacoes (
  id bigint generated by default as identity primary key,
  operacao_id bigint not null references operacoes(id) on delete cascade,
  token text not null unique,
  itens text not null default '[]',
  mensagem text not null default '',
  situacao text not null default 'aguardando' check (situacao in ('aguardando', 'em_analise', 'concluida', 'cancelada')),
  expira_em text not null,
  ultimo_envio_em text,
  criado_por text not null default '',
  criado_em text not null,
  atualizado_em text not null,
  cancelado_em text,
  cancelado_por text,
  concluida_em text
);
create unique index solicitacoes_aberta on solicitacoes (operacao_id) where situacao in ('aguardando', 'em_analise');

create table documentos (
  id bigint generated by default as identity primary key,
  operacao_id bigint not null references operacoes(id) on delete cascade,
  item_id bigint references operacao_itens(id) on delete set null,
  item_nome text not null default '',
  envio_id text not null,
  caminho text not null,
  arquivo_nome text not null default '',
  arquivo_tipo text not null default '',
  arquivo_tamanho bigint not null default 0,
  situacao text not null default 'aprovado' check (situacao in ('pendente', 'aprovado', 'recusado')),
  origem text not null default 'interno' check (origem in ('interno', 'link')),
  solicitacao_id bigint references solicitacoes(id) on delete set null,
  validade text,
  observacao text not null default '',
  lado text not null default '',
  motivo_recusa text not null default '',
  enviado_por text not null default '',
  analisado_por text,
  analisado_em text,
  excluido_em text,
  excluido_por text,
  criado_em text not null
);
create index documentos_operacao on documentos (operacao_id) where excluido_em is null;
create index documentos_situacao on documentos (situacao) where excluido_em is null;

create table historico (
  id bigint generated by default as identity primary key,
  quando text not null,
  usuario text not null default '',
  acao text not null,
  cliente_id bigint,
  operacao_id bigint,
  detalhe text not null default ''
);
create index historico_operacao on historico (operacao_id);
create index historico_cliente on historico (cliente_id);

create table modelo_etapas (
  id bigint generated by default as identity primary key,
  perfil_id bigint not null references perfis_documento(id) on delete cascade,
  nome text not null,
  prazo_dias integer not null default 0,
  ordem integer not null default 0,
  final integer not null default 0
);

create table operacao_etapas (
  id bigint generated by default as identity primary key,
  operacao_id bigint not null references operacoes(id) on delete cascade,
  nome text not null,
  prazo_dias integer not null default 0,
  ordem integer not null default 0,
  final integer not null default 0
);
create index operacao_etapas_operacao on operacao_etapas (operacao_id);

create table etapa_passagens (
  id bigint generated by default as identity primary key,
  operacao_id bigint not null references operacoes(id) on delete cascade,
  etapa_id bigint not null references operacao_etapas(id) on delete cascade,
  etapa_nome text not null,
  prazo_dias integer not null default 0,
  final integer not null default 0,
  consultor_id bigint references usuarios(id) on delete set null,
  consultor_nome text not null default '',
  entrou_em text not null,
  saiu_em text
);
create index etapa_passagens_operacao on etapa_passagens (operacao_id);
create index etapa_passagens_consultor on etapa_passagens (consultor_id);

create table transferencias (
  id bigint generated by default as identity primary key,
  operacao_id bigint not null references operacoes(id) on delete cascade,
  de_id bigint references usuarios(id) on delete set null,
  de_nome text not null default '',
  para_id bigint references usuarios(id) on delete set null,
  para_nome text not null default '',
  motivo text not null,
  por text not null default '',
  quando text not null
);
create index transferencias_operacao on transferencias (operacao_id);

create table lancamentos (
  id bigint generated by default as identity primary key,
  tipo text not null check (tipo in ('receita', 'despesa')),
  numero integer not null,
  descricao text not null,
  categoria text not null default '',
  valor_centavos bigint not null,
  vencimento text not null,
  pago_em text,
  cliente_id bigint references clientes(id) on delete set null,
  operacao_id bigint references operacoes(id) on delete set null,
  observacao text not null default '',
  criado_por text not null default '',
  criado_por_id bigint,
  criado_em text not null,
  atualizado_em text not null,
  excluido_em text,
  exemplo integer not null default 0
);
create index lancamentos_vencimento on lancamentos (vencimento) where excluido_em is null;

-- Ninguém de fora lê nem grava direto: tudo passa pela função do servidor.
do $$
declare t text;
begin
  foreach t in array array['perfis_acesso','usuarios','configuracoes','clientes','tipos_documento','perfis_documento',
    'perfis_documento_itens','operacoes','operacao_itens','solicitacoes','documentos','historico','modelo_etapas',
    'operacao_etapas','etapa_passagens','transferencias','lancamentos']
  loop
    execute format('alter table public.%I enable row level security', t);
  end loop;
end $$;

-- Os arquivos dos clientes: bucket privado, só a função do servidor acessa.
insert into storage.buckets (id, name, public) values ('documentos', 'documentos', false)
on conflict (id) do nothing;
